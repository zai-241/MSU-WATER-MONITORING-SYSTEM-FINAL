/**
 * @file reportExport.ts
 * @description Builds the Excel workbook and PDF document for the Reports page.
 * Extracted from Reports.tsx (Q1): these are pure document builders. They take the
 * already-computed report data and return a document; downloading, toasts and
 * loading state stay in the page.
 */
import { formatDateTime } from '@/lib/dateFormat';
import ExcelJS from 'exceljs';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { Tank, Log } from '@/store/useStore';
import { estimateVolumeLiters, tankCapacityLiters } from './constants';
import { emptyProblemCounts, PROBLEM_COLUMNS, type TelemetryTableRow } from './reportLogs';
import { hourRangeLabel, predictiveSummaryRows, PREDICTIVE_NOTE, type PredictiveReport } from './predictive';

/** jspdf-autotable records where the last table ended on the document */
type DocWithTable = jsPDF & { lastAutoTable: { finalY: number } };

export interface PumpActivityPoint {
  date: string;
  activations: number;
}

export interface ReportSummaryMetrics {
  avgLevel: number;
  minLevel: number;
  maxLevel: number;
  avgPh: number;
  minPh: number;
  maxPh: number;
  totalPumpRuns: number;
  alertsRegistered: number;
}

export interface ReportExportData {
  currentUser: { username?: string; email?: string } | null;
  dateRange: string;
  days: number;
  logs: Log[];
  pumpActivityData: PumpActivityPoint[];
  selectedTank: Tank;
  summaryMetrics: ReportSummaryMetrics | null;
  /** Rows of the Printable Telemetry Log Table: telemetry plus problem counts per period */
  telemetryData: TelemetryTableRow[];
  /** Include the pump rows, sheet and section (pump system on). Defaults to true. */
  includePump?: boolean;
  /** Configured alert thresholds, shown as the benchmarks in the summary */
  thresholds: { lowLevel: number; overflow: number; minPh: number; maxPh: number };
  /** Predictive analytics (same object as the Reports panel); omitted = no predictive sheet/section */
  predictive?: PredictiveReport;
}


/**
 * Sensor status of one history row. Readings recorded during a fault are kept
 * (monitoring continues), so the status column is what marks them.
 */
export function sensorStatusLabel(d: Pick<TelemetryTableRow, 'levelFault' | 'phFault' | 'hasSamples'>): string {
  if (d.hasSamples === false) return 'No data';
  if (d.levelFault && d.phFault) return 'Both Faulty';
  if (d.levelFault) return 'Level Fault';
  if (d.phFault) return 'pH Fault';
  return 'Normal';
}

export async function buildExcelWorkbook(data: ReportExportData): Promise<ExcelJS.Workbook> {
  const { currentUser, dateRange, days, logs, pumpActivityData, selectedTank, summaryMetrics, telemetryData, thresholds } = data;
  const includePump = data.includePump !== false;

  const workbook = new ExcelJS.Workbook();
  workbook.creator = currentUser?.username || 'MSU Water Monitoring System';
  workbook.created = new Date();

  const navyFill: ExcelJS.Fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF1E3A8A' }
  };
  const headerFont: Partial<ExcelJS.Font> = {
    name: 'Segoe UI',
    size: 11,
    bold: true,
    color: { argb: 'FFFFFFFF' }
  };
  const sectionFont: Partial<ExcelJS.Font> = {
    name: 'Segoe UI',
    size: 13,
    bold: true,
    color: { argb: 'FF1E3A8A' }
  };

  // 1. SUMMARY SHEET
  const summarySheet = workbook.addWorksheet('Summary', {
    views: [{ showGridLines: true }]
  });
  summarySheet.columns = [
    { width: 30 },
    { width: 32 },
    { width: 28 },
  ];

  const titleRow = summarySheet.addRow(['MSU MOTOR POOL - WATER MONITORING REPORT']);
  titleRow.font = { name: 'Segoe UI', size: 16, bold: true, color: { argb: 'FF1E3A8A' } };
  summarySheet.addRow([]);

  const metaHeader = summarySheet.addRow(['Report Information', '']);
  metaHeader.font = sectionFont;
  summarySheet.addRow(['Tank / Reservoir Name', selectedTank.name]);
  summarySheet.addRow(['Selected Time Window', dateRange]);
  summarySheet.addRow(['Generated By', currentUser?.username || currentUser?.email || 'System User']);
  summarySheet.addRow(['Generation Time', formatDateTime(Date.now(), { seconds: true })]);
  summarySheet.addRow([]);

  const metricsHeaderRow = summarySheet.addRow(['Summary Metric Parameter', 'Value', 'Operational Benchmark']);
  metricsHeaderRow.eachCell((cell) => {
    cell.fill = navyFill;
    cell.font = headerFont;
  });

  const metricsList = [
    ['Average Water Level', summaryMetrics?.avgLevel !== null && summaryMetrics?.avgLevel !== undefined ? `${summaryMetrics.avgLevel}%` : 'N/A', `Normal: ${thresholds.lowLevel}% - ${thresholds.overflow}%`],
    ['Minimum Water Level', summaryMetrics?.minLevel !== null && summaryMetrics?.minLevel !== undefined ? `${summaryMetrics.minLevel}%` : 'N/A', 'Observed Low'],
    ['Maximum Water Level', summaryMetrics?.maxLevel !== null && summaryMetrics?.maxLevel !== undefined ? `${summaryMetrics.maxLevel}%` : 'N/A', 'Observed High'],
    ['Average pH Level', summaryMetrics?.avgPh !== null && summaryMetrics?.avgPh !== undefined ? `${summaryMetrics.avgPh}` : 'N/A', `Safe: ${thresholds.minPh} - ${thresholds.maxPh}`],
    ['Minimum pH Level', summaryMetrics?.minPh !== null && summaryMetrics?.minPh !== undefined ? `${summaryMetrics.minPh}` : 'N/A', 'Observed Low'],
    ['Maximum pH Level', summaryMetrics?.maxPh !== null && summaryMetrics?.maxPh !== undefined ? `${summaryMetrics.maxPh}` : 'N/A', 'Observed High'],
    ...(includePump ? [['Pump Cycles (Runs)', summaryMetrics?.totalPumpRuns ?? 0, 'Pump starts in the period']] : []),
    ['Total System Alarms / Alerts', summaryMetrics?.alertsRegistered ?? 0, 'Registered Incidents'],
  ];

  metricsList.forEach(m => summarySheet.addRow(m));

  // 2. TELEMETRY HISTORY SHEET
  const historySheet = workbook.addWorksheet('Telemetry History', {
    views: [{ showGridLines: true }]
  });
  historySheet.columns = [
    { header: 'Date & Time', key: 'date', width: 24 },
    { header: 'Water Level (%)', key: 'waterLevel', width: 18 },
    { header: 'Water Height (m)', key: 'waterHeight', width: 18 },
    { header: 'pH Level', key: 'phLevel', width: 16 },
    { header: 'Estimated Volume (L)', key: 'volume', width: 22 },
    { header: 'Sample Count', key: 'sampleCount', width: 16 },
    { header: 'Sensor Status', key: 'status', width: 20 },
    ...PROBLEM_COLUMNS.map(c => ({ header: c.header, key: c.key, width: 20 })),
  ];

  const histHeader = historySheet.getRow(1);
  histHeader.eachCell((cell) => {
    cell.fill = navyFill;
    cell.font = headerFont;
    cell.alignment = { horizontal: 'center' };
  });

  telemetryData.forEach(item => {
    const status = sensorStatusLabel(item);
    const noData = item.hasSamples === false;

    historySheet.addRow({
      date: item.date,
      waterLevel: noData ? 'No data' : item.waterLevel !== null ? item.waterLevel : 'Sensor Fault',
      waterHeight: noData ? 'No data' : item.waterLevel !== null ? item.height : 'N/A',
      phLevel: noData ? 'No data' : item.phLevel !== null ? item.phLevel : 'Sensor Fault',
      volume: !noData && item.waterLevel !== null ? estimateVolumeLiters(item.waterLevel, tankCapacityLiters(selectedTank)) : 'N/A',
      sampleCount: item.sampleCount,
      status,
      ...(item.problems ?? emptyProblemCounts()),
    });
  });

  if (data.predictive) {
    // PREDICTIVE ANALYTICS SHEET
    const p = data.predictive;
    const sheet = workbook.addWorksheet('Predictive Analytics', { views: [{ showGridLines: true }] });
    sheet.columns = [{ width: 24 }, { width: 24 }, { width: 70 }, { width: 14 }];
    const title = sheet.addRow(['PREDICTIVE ANALYTICS']);
    title.font = { name: 'Segoe UI', size: 14, bold: true, color: { argb: 'FF1E3A8A' } };
    sheet.addRow([`${selectedTank.name}, ${dateRange}, ${p.profile.coveredDays} complete day(s) of history`]);
    sheet.addRow([PREDICTIVE_NOTE]);
    sheet.addRow([]);

    const header = (labels: string[]) => {
      const row = sheet.addRow(labels);
      row.eachCell((cell) => { cell.fill = navyFill; cell.font = headerFont; });
    };
    const highlight = (row: ExcelJS.Row) => row.eachCell((cell) => {
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFEF3C7' } };
      cell.font = { bold: true };
    });

    header(['Forecast', 'Result', 'Details']);
    predictiveSummaryRows(p, thresholds.lowLevel).forEach(r => sheet.addRow(r));
    sheet.addRow([]);

    const peakHours = new Set(p.profile.peakHours.map(h => h.hour));
    sheet.addRow(['Average water use by hour of the day']).font = sectionFont;
    header(['Hour', 'Average Use (L)', 'Average Use (% of tank)', 'Days']);
    p.profile.hours.forEach(h => {
      const row = sheet.addRow([hourRangeLabel(h.hour), h.avgLiters ?? 'No data', h.avgPercent ?? 'No data', h.days]);
      if (peakHours.has(h.hour)) highlight(row);
    });
    sheet.addRow([]);

    sheet.addRow(['Average water use by day of the week']).font = sectionFont;
    header(['Day', 'Average Use (L/day)', 'Average Use (% of tank)', 'Days']);
    p.profile.weekdays.forEach(w => {
      const row = sheet.addRow([w.name, w.avgLiters ?? 'No complete day', w.avgPercent ?? 'No complete day', w.days]);
      if (p.profile.peakWeekday?.weekday === w.weekday) highlight(row);
    });
    sheet.addRow([]);
    sheet.addRow(['Highlighted rows: the peak hours and the peak day.']);
  }

  if (includePump) {
    // 3. PUMP ACTIVITY SHEET
    const pumpSheet = workbook.addWorksheet('Pump Activity', {
      views: [{ showGridLines: true }]
    });
    pumpSheet.columns = [
      { header: 'Date', key: 'date', width: 20 },
      { header: 'Activation Cycles', key: 'activations', width: 22 },
      { header: 'Operational Status', key: 'status', width: 22 },
    ];

    const pumpHeader = pumpSheet.getRow(1);
    pumpHeader.eachCell((cell) => {
      cell.fill = navyFill;
      cell.font = headerFont;
      cell.alignment = { horizontal: 'center' };
    });

    pumpActivityData.forEach(item => {
      pumpSheet.addRow({
        date: item.date,
        activations: item.activations,
        status: item.activations > 0 ? 'Active' : 'Idle',
      });
    });
  }

  // 4. ALERT LOGS SHEET
  const alertSheet = workbook.addWorksheet('Alert Logs', {
    views: [{ showGridLines: true }]
  });
  alertSheet.columns = [
    { header: 'Timestamp', key: 'timestamp', width: 24 },
    { header: 'Severity Level', key: 'logLevel', width: 18 },
    { header: 'Action / Event', key: 'action', width: 28 },
    { header: 'Log Details', key: 'details', width: 45 },
    { header: 'Performed By / Source', key: 'performedBy', width: 24 },
  ];

  const alertHeader = alertSheet.getRow(1);
  alertHeader.eachCell((cell) => {
    cell.fill = navyFill;
    cell.font = headerFont;
    cell.alignment = { horizontal: 'center' };
  });

  const cutoff = Date.now() - days * 24 * 60 * 60 * 1000;
  const relevantLogs = logs.filter(l => {
    const t = new Date(l.timestamp).getTime();
    return t >= cutoff && (
      l.logLevel === 'WARNING' ||
      l.logLevel === 'ERROR' ||
      l.logLevel === 'CRITICAL' ||
      l.action.toLowerCase().includes('alert') ||
      l.action.toLowerCase().includes('fault') ||
      l.action.toLowerCase().includes('alarm')
    );
  });

  if (relevantLogs.length === 0) {
    alertSheet.addRow({
      timestamp: formatDateTime(Date.now(), { seconds: true }),
      logLevel: 'INFO',
      action: 'Normal Operation',
      details: 'No system alarms or warnings recorded in selected time window.',
      performedBy: 'System',
    });
  } else {
    relevantLogs.forEach(l => {
      alertSheet.addRow({
        timestamp: formatDateTime(l.timestamp, { seconds: true }),
        logLevel: l.logLevel || 'WARNING',
        action: l.action,
        details: l.details,
        performedBy: l.performedBy || 'System',
      });
    });
  }

  return workbook;
}

export function buildPdfDocument(data: ReportExportData): jsPDF {
  const { currentUser, dateRange, days, logs, pumpActivityData, selectedTank, summaryMetrics, telemetryData, thresholds } = data;
  const includePump = data.includePump !== false;

  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const primaryColor: [number, number, number] = [30, 58, 138];
  const grayColor: [number, number, number] = [100, 116, 139];

  // Document Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.setTextColor(...primaryColor);
  doc.text('MSU MOTOR POOL', 14, 18);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(...grayColor);
  doc.text('Water Reservoir Monitoring & Telemetry Report', 14, 25);

  // Divider line
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(14, 28, 196, 28);

  // Metadata Block
  doc.setFontSize(9);
  doc.setTextColor(30, 41, 59);
  doc.text(`Tank / Reservoir: ${selectedTank.name}`, 14, 34);
  doc.text(`Date Range: ${dateRange}`, 14, 39);
  doc.text(`Generated By: ${currentUser?.username || currentUser?.email || 'System User'}`, 120, 34);
  doc.text(`Generation Time: ${formatDateTime(Date.now(), { seconds: true })}`, 120, 39);

  let currentY = 45;

  // 1. EXECUTIVE SUMMARY TABLE
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(...primaryColor);
  doc.text('1. Executive Telemetry Summary', 14, currentY);

  const summaryTableRows = [
    ['Average Water Level', summaryMetrics?.avgLevel !== null && summaryMetrics?.avgLevel !== undefined ? `${summaryMetrics.avgLevel}%` : 'N/A', `Target: ${thresholds.lowLevel}% - ${thresholds.overflow}%`],
    ['Water Level Range', summaryMetrics ? `${summaryMetrics.minLevel}% - ${summaryMetrics.maxLevel}%` : 'N/A', 'Observed extremes'],
    ['Average pH Value', summaryMetrics?.avgPh !== null && summaryMetrics?.avgPh !== undefined ? `${summaryMetrics.avgPh}` : 'N/A', `Safe range: ${thresholds.minPh} - ${thresholds.maxPh}`],
    ['pH Value Range', summaryMetrics ? `${summaryMetrics.minPh} - ${summaryMetrics.maxPh}` : 'N/A', 'Observed extremes'],
    ...(includePump ? [['Pump Cycles (Runs)', summaryMetrics?.totalPumpRuns !== undefined ? `${summaryMetrics.totalPumpRuns} cycles` : '0 cycles', 'Pump starts in the period']] : []),
    ['Total Alarms & Incidents', summaryMetrics?.alertsRegistered !== undefined ? `${summaryMetrics.alertsRegistered}` : '0', 'System warnings'],
  ];

  autoTable(doc, {
    startY: currentY + 3,
    head: [['Metric Parameter', 'Recorded Value', 'Operational Context']],
    body: summaryTableRows,
    theme: 'striped',
    headStyles: { fillColor: primaryColor, textColor: 255, fontSize: 9, fontStyle: 'bold' },
    bodyStyles: { fontSize: 8.5, textColor: [30, 41, 59] },
    margin: { left: 14, right: 14 },
  });

  currentY = (doc as DocWithTable).lastAutoTable.finalY + 10;

  // 2. TELEMETRY HISTORY TABLE
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(...primaryColor);
  doc.text('2. Water Level & pH History (/history)', 14, currentY);

  const historyRows = telemetryData.map((d) => {
    const statusStr = sensorStatusLabel(d);
    const noData = d.hasSamples === false;
    const problems = d.problems ?? emptyProblemCounts();

    return [
      d.date,
      noData ? 'No data' : d.waterLevel !== null ? `${d.waterLevel}%` : 'Sensor Fault',
      noData ? '-' : d.waterLevel !== null ? `${d.height} m` : 'N/A',
      noData ? 'No data' : d.phLevel !== null ? `${d.phLevel}` : 'Sensor Fault',
      !noData && d.waterLevel !== null ? `${estimateVolumeLiters(d.waterLevel, tankCapacityLiters(selectedTank)).toLocaleString()} L` : 'N/A',
      String(d.sampleCount),
      statusStr,
      ...PROBLEM_COLUMNS.map(c => String(problems[c.key])),
    ];
  });

  // Eleven columns: smaller type, and the problem counts centred in narrow columns
  autoTable(doc, {
    startY: currentY + 3,
    head: [['Date / Time', 'Water Level', 'Height', 'pH Level', 'Est. Volume', 'Samples', 'Status', 'Level Sensor Fault', 'pH Sensor Fault', 'Controller Offline', 'Other Problems']],
    body: historyRows,
    theme: 'grid',
    headStyles: { fillColor: primaryColor, textColor: 255, fontSize: 7, fontStyle: 'bold', valign: 'middle' },
    bodyStyles: { fontSize: 7, textColor: [30, 41, 59] },
    columnStyles: {
      7: { halign: 'center', cellWidth: 14 },
      8: { halign: 'center', cellWidth: 14 },
      9: { halign: 'center', cellWidth: 15 },
      10: { halign: 'center', cellWidth: 15 },
    },
    // Problem counts above 0 in red, as on the page
    didParseCell: (cell) => {
      if (cell.section === 'body' && cell.column.index >= 7 && cell.cell.raw !== '0') {
        cell.cell.styles.textColor = [220, 38, 38];
        cell.cell.styles.fontStyle = 'bold';
      }
    },
    margin: { left: 14, right: 14 },
  });

  currentY = (doc as DocWithTable).lastAutoTable.finalY + 10;

  let section = 3;

  if (data.predictive) {
    // PREDICTIVE ANALYTICS: summary, then use by hour (two columns of 12) and by day
    const p = data.predictive;
    if (currentY > 200) {
      doc.addPage();
      currentY = 20;
    }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(...primaryColor);
    doc.text(`${section++}. Predictive Analytics`, 14, currentY);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(...grayColor);
    const note: string[] = doc.splitTextToSize(`${PREDICTIVE_NOTE} Based on ${p.profile.coveredDays} complete day(s).`, 182);
    doc.text(note, 14, currentY + 5);
    currentY += 5 + note.length * 3.2;

    autoTable(doc, {
      startY: currentY + 1,
      head: [['Forecast', 'Result', 'Details']],
      body: predictiveSummaryRows(p, thresholds.lowLevel),
      theme: 'striped',
      headStyles: { fillColor: primaryColor, textColor: 255, fontSize: 8.5, fontStyle: 'bold' },
      bodyStyles: { fontSize: 8, textColor: [30, 41, 59] },
      columnStyles: { 0: { fontStyle: 'bold', cellWidth: 36 }, 1: { cellWidth: 36 } },
      margin: { left: 14, right: 14 },
    });
    currentY = (doc as DocWithTable).lastAutoTable.finalY + 6;

    const peakHours = new Set(p.profile.peakHours.map(h => h.hour));
    const fmt = (v: number | null, empty: string) => (v === null ? empty : `${v} L`);
    if (p.enoughData) {
      if (currentY > 200) {
        doc.addPage();
        currentY = 20;
      }
      const hourRows = Array.from({ length: 12 }, (_, i) => {
        const a = p.profile.hours[i];
        const b = p.profile.hours[i + 12];
        return [hourRangeLabel(a.hour), fmt(a.avgLiters, '-'), hourRangeLabel(b.hour), fmt(b.avgLiters, '-')];
      });
      autoTable(doc, {
        startY: currentY,
        head: [['Hour', 'Avg. Use', 'Hour', 'Avg. Use']],
        body: hourRows,
        theme: 'grid',
        headStyles: { fillColor: primaryColor, textColor: 255, fontSize: 8, fontStyle: 'bold' },
        bodyStyles: { fontSize: 7.5, textColor: [30, 41, 59] },
        // Peak hours highlighted, as on the page
        didParseCell: (cell) => {
          if (cell.section !== 'body') return;
          const hour = cell.row.index + (cell.column.index >= 2 ? 12 : 0);
          if (peakHours.has(hour)) {
            cell.cell.styles.fillColor = [254, 243, 199];
            cell.cell.styles.fontStyle = 'bold';
          }
        },
        margin: { left: 14, right: 14 },
      });
      currentY = (doc as DocWithTable).lastAutoTable.finalY + 6;
    }

    if (currentY > 230) {
      doc.addPage();
      currentY = 20;
    }
    autoTable(doc, {
      startY: currentY,
      head: [['Day of the Week', 'Avg. Use per Day', 'Days']],
      body: p.profile.weekdays.map(w => [w.name, fmt(w.avgLiters, 'No complete day'), String(w.days)]),
      theme: 'grid',
      headStyles: { fillColor: primaryColor, textColor: 255, fontSize: 8, fontStyle: 'bold' },
      bodyStyles: { fontSize: 7.5, textColor: [30, 41, 59] },
      didParseCell: (cell) => {
        if (cell.section === 'body' && p.profile.weekdays[cell.row.index].weekday === p.profile.peakWeekday?.weekday) {
          cell.cell.styles.fillColor = [254, 243, 199];
          cell.cell.styles.fontStyle = 'bold';
        }
      },
      margin: { left: 14, right: 14 },
    });
    currentY = (doc as DocWithTable).lastAutoTable.finalY + 10;
  }

  if (includePump) {
    // PUMP ACTIVITY TABLE
    if (currentY > 230) {
      doc.addPage();
      currentY = 20;
    }

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(...primaryColor);
    doc.text(`${section++}. Pump Activity`, 14, currentY);

    const pumpRows = pumpActivityData.map(p => [
      p.date,
      `${p.activations} cycles`,
      p.activations > 0 ? 'Active' : 'Idle',
    ]);

    autoTable(doc, {
      startY: currentY + 3,
      head: [['Date', 'Activation Cycles', 'Operational Status']],
      body: pumpRows,
      theme: 'striped',
      headStyles: { fillColor: primaryColor, textColor: 255, fontSize: 8.5, fontStyle: 'bold' },
      bodyStyles: { fontSize: 8, textColor: [30, 41, 59] },
      margin: { left: 14, right: 14 },
    });

    currentY = (doc as DocWithTable).lastAutoTable.finalY + 10;
  }

  // ALARM & INCIDENT LOGS TABLE
  if (currentY > 230) {
    doc.addPage();
    currentY = 20;
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(...primaryColor);
  doc.text(`${section}. System Alarms & Incident Logs`, 14, currentY);

  const cutoff = Date.now() - days * 24 * 60 * 60 * 1000;
  const relevantLogs = logs.filter(l => {
    const t = new Date(l.timestamp).getTime();
    return t >= cutoff && (
      l.logLevel === 'WARNING' ||
      l.logLevel === 'ERROR' ||
      l.logLevel === 'CRITICAL' ||
      l.action.toLowerCase().includes('alert') ||
      l.action.toLowerCase().includes('fault') ||
      l.action.toLowerCase().includes('alarm')
    );
  });

  const alertRows = relevantLogs.length > 0
    ? relevantLogs.slice(0, 20).map(l => [
        formatDateTime(l.timestamp, { seconds: true }),
        l.logLevel || 'WARNING',
        l.action,
        l.details,
      ])
    : [['-', 'INFO', 'Normal Operation', 'No active warnings or incidents logged for this time window.']];

  autoTable(doc, {
    startY: currentY + 3,
    head: [['Timestamp', 'Severity', 'Action', 'Details']],
    body: alertRows,
    theme: 'striped',
    headStyles: { fillColor: primaryColor, textColor: 255, fontSize: 8.5, fontStyle: 'bold' },
    bodyStyles: { fontSize: 7.5, textColor: [30, 41, 59] },
    margin: { left: 14, right: 14 },
  });

  // Page numbers footer
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `MSU Motor Pool Water Monitoring System • Page ${i} of ${pageCount}`,
      14,
      290
    );
  }

  return doc;
}
